-- Run this in Supabase SQL Editor (Dashboard → SQL Editor) to create orders + order_items.
-- Then set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in Vercel / .env.local.

-- Orders (same shape as Directus)
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  status text not null default 'pending' check (status in ('pending', 'paid', 'cancelled')),
  total numeric(10,2) not null,
  currency text default 'USD',
  date_created timestamptz default now(),
  paypal_order_id text,
  pocketbase_order_id text
);

-- Order line items
create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  sku text not null,
  name text not null,
  quantity int not null default 1,
  price numeric(10,2) not null
);

create index if not exists order_items_order_id_idx on public.order_items(order_id);

-- Optional: restrict direct table access to service role (your app uses service role key)
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

create policy "Service role full access orders" on public.orders
  for all using (true) with check (true);

create policy "Service role full access order_items" on public.order_items
  for all using (true) with check (true);

-- Products catalog (optional): add rows in Table Editor to show on the store.
-- When NEXT_PUBLIC_SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY are set, store uses these if table has rows.
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  sku text not null,
  name text not null,
  price numeric(10,2) not null,
  category text not null default 'Best Seller',
  short_description text,
  description text,
  suggested_use text,
  supplement_facts text,
  ingredients text,
  upc text,
  gtin text,
  weight text,
  dimensions text,
  key_search_terms text,
  faqs jsonb default '[]'::jsonb,
  image text,
  images jsonb default '[]'::jsonb,
  sort_order int default 0,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create index if not exists products_slug_idx on public.products(slug);
create index if not exists products_sku_idx on public.products(sku);
create index if not exists products_sort_idx on public.products(sort_order);

alter table public.products enable row level security;
create policy "Service role full access products" on public.products
  for all using (true) with check (true);
